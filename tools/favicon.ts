/**
 * favicon: write the tab icon, public/favicon.svg, from its drawing (app/art/tab-icon.ts).
 *
 *   ./node_modules/.bin/tsx tools/favicon.ts        (or: pnpm favicon)
 *   ./node_modules/.bin/tsx tools/favicon.ts --png .snaps/icon.png   also a PNG, to look at
 *
 * The icon is pixel art, 32 x 32. The file is an SVG that holds it as a picture (a PNG,
 * magnified four times with hard edges, as a data URI), not as shapes. A tab shows the icon
 * at 16 pixels, half its size: scaled as a picture it is averaged down cleanly, where the
 * same pixels as SVG rectangles break up (with hard edges whole rows of pixels are dropped,
 * and smoothed the seams between the rectangles show). Magnified four times, every size up
 * to 128 is a scaling down, and 32 and 64 come out exact.
 *
 * It stays an SVG, under the name it had, because the game clock asks the server the time
 * with a HEAD request to /favicon.svg (app/ui/game-clock.ts).
 */

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { TAB_ICON_SIZE, drawTabIcon } from "~/art/tab-icon";

import { encodePng } from "./png";

/** How many times the picture is magnified in the file. */
export const FAVICON_SCALE = 4;

/** The file's text. */
export function faviconSvg(): string {
  const size = TAB_ICON_SIZE;
  const png = encodePng(drawTabIcon(), FAVICON_SCALE).toString("base64");
  return [
    "<!--",
    "  The tab icon: the home screen's football with an italic SS in front of it.",
    "  Pixel art, 32 x 32, drawn in app/art/tab-icon.ts. Do not edit this file:",
    "  change the drawing and run `pnpm favicon` (tools/favicon.ts), which says why",
    "  the picture is held here as a PNG and not as shapes.",
    "-->",
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><image width="${size}" height="${size}" href="data:image/png;base64,${png}"/></svg>`,
    "",
  ].join("\n");
}

function main(): void {
  const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
  const out = path.join(root, "public", "favicon.svg");
  const svg = faviconSvg();
  writeFileSync(out, svg);
  console.log(`${out}  ${svg.length} bytes`);
  const at = process.argv.indexOf("--png");
  if (at >= 0 && process.argv[at + 1]) {
    const png = path.resolve(process.argv[at + 1]);
    writeFileSync(png, encodePng(drawTabIcon(), 8));
    console.log(`${png}  ${TAB_ICON_SIZE * 8} px`);
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}

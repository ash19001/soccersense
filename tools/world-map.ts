/**
 * Makes the world map's land and sea (app/art/world-map-data.ts) from Natural Earth's land
 * polygons (public domain: naturalearthdata.com, the 1:50m "land" layer as GeoJSON, from
 * github.com/nvkelso/natural-earth-vector, geojson/ne_50m_land.geojson).
 *
 *   ./node_modules/.bin/tsx tools/world-map.ts <ne_50m_land.geojson>
 *
 * The world is cut into cells half a degree on a side, from 180 degrees west eastwards and
 * from `NORTH` southwards to `SOUTH` (the far north and the Antarctic are left out: nothing
 * the game asks about is there). A cell is land when its centre is inside a polygon (even
 * and odd crossings along its row). Each row is written as the lengths of its runs, sea
 * first, in base 36, so the data is a few kilobytes of text.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PER_DEGREE = 2;
const NORTH = 84;
const SOUTH = -60;
const COLS = 360 * PER_DEGREE;
const ROWS = (NORTH - SOUTH) * PER_DEGREE;

type Ring = [number, number][];

const source = process.argv[2];
if (!source) {
  console.error("usage: tsx tools/world-map.ts <ne_50m_land.geojson>");
  process.exit(1);
}
const geo = JSON.parse(readFileSync(source, "utf8")) as {
  features: { geometry: { type: string; coordinates: unknown } }[];
};

const rings: Ring[] = [];
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry;
  const polygons =
    type === "Polygon"
      ? [coordinates as Ring[]]
      : type === "MultiPolygon"
        ? (coordinates as Ring[][])
        : [];
  for (const polygon of polygons) for (const ring of polygon) rings.push(ring);
}

const land = new Uint8Array(COLS * ROWS);
for (let row = 0; row < ROWS; row++) {
  const lat = NORTH - (row + 0.5) / PER_DEGREE;
  const crossings: number[] = [];
  for (const ring of rings) {
    for (let i = 0; i < ring.length - 1; i++) {
      const [x0, y0] = ring[i];
      const [x1, y1] = ring[i + 1];
      if (y0 > lat === y1 > lat) continue;
      crossings.push(x0 + ((lat - y0) / (y1 - y0)) * (x1 - x0));
    }
  }
  crossings.sort((a, b) => a - b);
  for (let k = 0; k + 1 < crossings.length; k += 2) {
    const from = Math.ceil((crossings[k] + 180) * PER_DEGREE - 0.5);
    const to = Math.floor((crossings[k + 1] + 180) * PER_DEGREE - 0.5);
    for (let col = Math.max(0, from); col <= Math.min(COLS - 1, to); col++) {
      land[row * COLS + col] = 1;
    }
  }
}

const lines: string[] = [];
for (let row = 0; row < ROWS; row++) {
  const runs: number[] = [];
  let value = 0;
  let length = 0;
  for (let col = 0; col < COLS; col++) {
    const cell = land[row * COLS + col];
    if (cell === value) {
      length++;
    } else {
      runs.push(length);
      value = cell;
      length = 1;
    }
  }
  runs.push(length);
  lines.push(runs.map((n) => n.toString(36)).join(","));
}

const out = `// Generated by tools/world-map.ts from Natural Earth's 1:50m land polygons (public
// domain, naturalearthdata.com). Do not edit by hand: run the tool again.
//
// The world in cells half a degree on a side, from 180 degrees west eastwards and from
// WORLD_NORTH southwards to WORLD_SOUTH. Each row is the lengths of its runs, sea first,
// in base 36, separated by commas; rows are separated by "|". Read by ./world-map.ts.

export const WORLD_PER_DEGREE = ${PER_DEGREE};
export const WORLD_NORTH = ${NORTH};
export const WORLD_SOUTH = ${SOUTH};
export const WORLD_COLS = ${COLS};
export const WORLD_ROWS = ${ROWS};

export const WORLD_RUNS =
  ${JSON.stringify(lines.join("|"))};
`;
const target = join(process.cwd(), "app/art/world-map-data.ts");
writeFileSync(target, out);
const landShare = land.reduce((n, c) => n + c, 0) / land.length;
console.log(
  `wrote ${target}: ${COLS} x ${ROWS} cells, ${Math.round(landShare * 100)}% land, ${out.length} characters`,
);

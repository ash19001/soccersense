let small: BitmapFont | undefined;
let big: BitmapFont | undefined;

/** The small painted face: capitals 10 px tall, digits and punctuation. Caps only. */
export function font6x10(): BitmapFont {
  return (small ??= buildFont(
    {
      name: "FONT_6x10",
      height: 12,
      capHeight: 10,
      lineHeight: 14,
      spacing: 2,
      spaceWidth: 4,
      upperOnly: true,
    },
    SHEETS_6x10,
  ));
}

/** The main painted face: capitals 14 px tall, lowercase with descenders, full ASCII. */
export function font10x14(): BitmapFont {
  return (big ??= buildFont(
    {
      name: "FONT_10x14",
      height: 18,
      capHeight: 14,
      lineHeight: 20,
      spacing: 2,
      spaceWidth: 6,
      upperOnly: false,
    },
    SHEETS_10x14,
  ));
}

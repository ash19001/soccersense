/**
 * The painted faces (docs/ART_BIBLE.md section 7): the two small faces (`FONT_3x5`,
 * `FONT_5x7`) drawn again, natively, with twice the pixels.
 *
 * - `FONT_6x10`: the small face, `FONT_3x5`'s twin. Capitals 10 px tall with 2 px stems,
 *   digits and the same punctuation; lowercase draws as capitals.
 * - `FONT_10x14`: the main face, `FONT_5x7`'s twin. Capitals 14 px tall, lowercase with a
 *   10 px x-height and descenders 4 px below the baseline, full ASCII and the middle dot.
 *
 * Every glyph is exactly twice as wide as its twin and the spacing, the space and the line
 * height are doubled too, so a line measures exactly twice what it does in its twin
 * (`measureText`, `wrapText`, `drawText` with `tabular`, `outline`, `shadow` and `align`
 * work on them unchanged; the outline and the shadow are 1 px, as every outline is). They
 * are for painted words (the menu ball's labels, the wordmark's tagline, boards, banners,
 * "POP!"). Lit lamps (LED boards, the airship's sign, scoreboards) use the small faces as
 * lamps instead (`drawLamps`, ~/art/led).
 *
 * The 2 px strokes keep the twins' weight on screen; the extra pixels go into the
 * shapes: rounded bowls and shoulders, clean 45 degree joins, real diagonals in K, N, V,
 * W, X, Z, 2 and 7.
 *
 * The art reaches them through `paintedFont` (~/art/lettering).
 */


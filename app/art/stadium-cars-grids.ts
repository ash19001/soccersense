/**
 * The car and coach drawings, as data: one grid of letters per drawn
 * heading and size class, and the anchor (the ground point under the vehicle's middle).
 * Traced once from a small model of a car and a coach in the picture's own oblique view
 * (.snaps/detail2/g/gen-vehicles.ts, after the mockup), then cleaned by hand: this file is the drawing now, edit it here.
 *
 * A car class holds 7 headings, 0 to 6 (east round to north, 15 degrees apart); a coach
 * class 14, those and 12 to 18 (west round to south). stadium-cars.ts makes the rest by
 * turning the cars round and mirroring.
 *
 *   day   b body          l roof          d side in shade      n deep shade (sill, bumper)
 *         f windscreen    r rear window   g side glass         w glass catching the sky
 *         k tyre          m hub           y headlamp           q tail lamp
         (the far and middle cars) Y, Q a headlamp or tail lamp on the top, H, T on an
         end: dark by day (body, side), lit at night
 *         (coaches) o roof   s side   e stripe
 *         i roof edge in the light, j the west edge (lit unless mirrored), J the east
 *         edge (lit only when mirrored)
 *   At night the y and q lamps glow (headlights and tail lights), and a driving car
 *   throws a beam on the road ahead (`beam`).
 *
 * Pure data.
 */

export interface Grid {
  readonly day: readonly string[];
  /** The ground point under the middle, in the grid. */
  readonly ax: number;
  readonly ay: number;
  /** The beam on the road ahead at night, as offsets from the ground point. */
  readonly beam: readonly (readonly [number, number])[];
}

function grid(
  ax: number,
  ay: number,
  beam: readonly (readonly [number, number])[],
  day: readonly string[],
): Grid {
  return { day, ax, ay, beam };
}


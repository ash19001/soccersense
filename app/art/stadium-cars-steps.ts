/**
 * The in-between sizes of the cars and coaches (package G2), as data: a car or a coach
 * shrinks in five steps as it gets further away (the three size classes are steps 0, 2
 * and 4, in stadium-cars-grids.ts; these are steps 1 and 3), so it
 * never jumps from one size to the next. A step-1 car is 8 px long pointing east and a
 * step-3 car 12 (steps 0, 2, 4: 6, 10, 14); a step-1 coach 17 and a step-3 coach 29
 * (12, 23, 35). Same letters, headings and anchors as stadium-cars-grids.ts.
 *
 * Traced once from the same small models as the other steps (.snaps/detail2/g2/gen-fine.ts,
 * after G's tracer, at the in-between sizes), then cleaned by hand to match their
 * neighbours: this file is the drawing now, edit it here.
 *
 * Pure data.
 */

import type { Grid } from "~/art/stadium-cars-grids";

function grid(
  ax: number,
  ay: number,
  beam: readonly (readonly [number, number])[],
  day: readonly string[],
): Grid {
  return { day, ax, ay, beam };
}

